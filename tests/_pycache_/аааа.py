print("Добро пожаловать в мой калькулятор! ")
а = float(input("Введи первое число: "))
b = float(input("Введи второе число: "))
op = input("Выбери операцию (+, -, *,/): ")

if op == "+":
    print(f"Результат: {а + b}")
elif op == "-":
    print(f"Результат: {а - b}")
elif op == "*":
    print(f"Результат: {а* b}")
elif op == "/":
    if b != 0:
        print(f"Результат: {а/ b}")
    else:
        print("Ошибка! Делить на ноль нельзя!")
else:
    print("Не понимаю эту операцию")
